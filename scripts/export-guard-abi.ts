// Copies the PayrollGuard ABI from contracts/out into src/server/arc/guard-abi.ts. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";

const artifact = JSON.parse(readFileSync("contracts/out/PayrollGuard.sol/PayrollGuard.json", "utf8"));
writeFileSync(
  "src/server/arc/guard-abi.ts",
  `import "server-only";\n// Generated by scripts/export-guard-abi.ts. Do not edit.\nexport const guardAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log("wrote src/server/arc/guard-abi.ts");
