// S33: real repositories/authenticated handlers and DB, fake AI/Circle/Arc ports. This is not live settlement evidence.
import { randomUUID } from "node:crypto";
import { expect, it } from "vitest";
import { POST as importRoute } from "@/app/api/imports/route";
import { POST as calculateRoute } from "@/app/api/runs/[id]/calculate/route";
import { POST as submitRoute } from "@/app/api/runs/[id]/submit/route";
import { proposeConfig } from "@/server/ai/policy";
import { configAction } from "@/server/db/configs";
import { approveRun } from "@/server/db/approval";
import { proposeBatch, signBatch } from "@/server/db/batches";
import { paymentsRepo } from "@/server/db/payments-repo";
import { reconcileRun, resolveException } from "@/server/db/reconciliation";
import { runDeps } from "@/server/db/runs";
import { createWorker, setWorkerWallet } from "@/server/db/workers";
import { openJson } from "@/server/crypto";
import { executeBatch } from "@/server/payments/execute";
import { createRun } from "@/core/workflow";
import { parseUsdc } from "@/core/money";
import { GOOD, POLICY_TEXT, scripted } from "../fixtures/ai/policy";
import { ADDR, admin, call, cookieFor, makeCompany, withId } from "./helpers";
import { agentDepsFor, DbChain, DbRail, FakePort } from "./payment-fakes";

it("joins distinct request support codes to immutable policy, evidence, approval, payment attempt and receipt", async () => {
  const company = await makeCompany({ live: true });
  const requestIds = new Set<string>();
  const who = (payment = false) => {
    const correlationId = randomUUID();
    requestIds.add(correlationId);
    const u = payment ? company.payment : company.payroll;
    return { companyId: company.id, userId: u.id, roles: u.roles, correlationId };
  };
  const proposal = await proposeConfig(who(), POLICY_TEXT, scripted([GOOD]));
  expect(proposal.config).not.toBeNull();
  const configId = proposal.config!.id;
  await configAction(who(), configId, "approve");
  await configAction(who(), configId, "activate");
  const worker = await createWorker(who(), { pseudonym: "W901", payType: "SALARIED", compensation: { baseAmount: parseUsdc("5"), hourlyRate: 0n } });
  await setWorkerWallet(company.id, worker.id, { walletId: randomUUID(), address: ADDR(901), source: "CIRCLE" });
  const run = await createRun(runDeps, who(), { mode: "LIVE_TESTNET", periodStart: "2026-10-05", periodEnd: "2026-10-11" });
  const { cookie } = await cookieFor(company.payroll);
  const capture = async (response: Response) => {
    expect(response.status).toBe(200);
    const id = response.headers.get("x-correlation-id")!;
    expect(id).toMatch(/^[0-9a-f-]{36}$/);
    expect(requestIds.has(id)).toBe(false);
    requestIds.add(id);
    return id;
  };
  const imported = await call(importRoute, { cookie, path: "/api/imports", body: { runId: run.id, type: "TIMESHEETS", mapping: { workerRef: 0, date: 1, hours: 2, approvedExtraHours: 3 }, items: Array.from({ length: 5 }, (_, i) => ({ row: i + 2, data: { workerRef: "W901", date: `2026-10-0${i + 5}`, hours: "8", approvedExtraHours: "0" } })) } });
  const importCorrelation = await capture(imported);
  const offline = scripted([new Error("provider deliberately unavailable")]);
  await reconcileRun(who(), run.id, offline);
  const exceptions = (await admin.from("exceptions").select("id").eq("run_id", run.id).in("status", ["OPEN", "IN_REVIEW"])).data!;
  expect(exceptions).toHaveLength(1);
  await resolveException(who(), exceptions[0].id, { action: "TREAT_AS_PAID_LEAVE", note: "Synthetic human decision after reviewing the missing-time evidence" }, offline);
  const calculationCorrelation = await capture(await call(calculateRoute, { cookie, path: `/api/runs/${run.id}/calculate` }, withId(run.id)));
  await capture(await call(submitRoute, { cookie, path: `/api/runs/${run.id}/submit` }, withId(run.id)));
  await approveRun(who(), run.id);
  const { batchId } = await proposeBatch(who(true), run.id, []);
  await signBatch(who(true), batchId, new FakePort());
  const chain = new DbChain();
  await chain.commitBatch(batchId);
  const rail = new DbRail(chain);
  const executor = who(true);
  await executeBatch(executor, batchId, { deps: { ...agentDepsFor(chain, rail), repo: paymentsRepo(executor.correlationId) } });

  const config = (await admin.from("payroll_configurations").select("ai_execution_id").eq("id", configId).single()).data!;
  expect(config.ai_execution_id).toBe(proposal.executionId);
  const execution = (await admin.from("ai_executions").select("correlation_id").eq("id", proposal.executionId).single()).data!;
  expect(requestIds.has(execution.correlation_id)).toBe(true);
  const calc = (await admin.from("calculations").select("id, calculation_hash, snapshot_enc").eq("run_id", run.id).single()).data!;
  const snapshot = await openJson<{ evidence: { timesheets: { id: string; source_hash: string }[] }; decisions: Record<string, string> }>(company.id, "calculations", "snapshot_enc", calc.id, calc.snapshot_enc);
  const sourceRows = (await admin.from("timesheets").select("id, source_hash, import_batch_id").eq("run_id", run.id)).data!;
  expect(snapshot.evidence.timesheets).toHaveLength(5);
  expect(snapshot.evidence.timesheets.map(e => e.id).sort()).toEqual(sourceRows.map(e => e.id).sort());
  expect(snapshot.evidence.timesheets.map(e => e.source_hash).sort()).toEqual(sourceRows.map(e => e.source_hash).sort());
  expect(Object.values(snapshot.decisions)).toContain("TREAT_AS_PAID_LEAVE");
  const approval = (await admin.from("payroll_approvals").select("id,calculation_id,calculation_hash,approver_id").eq("run_id", run.id).single()).data!;
  expect(approval).toMatchObject({ calculation_id: calc.id, calculation_hash: calc.calculation_hash, approver_id: company.payroll.id });
  const obligation = (await admin.from("obligations").select("id,approval_id,calculation_line_id,batch_id,status,tx_hash,idempotency_key").eq("run_id", run.id).single()).data!;
  expect(obligation).toMatchObject({ approval_id: approval.id, batch_id: batchId, status: "SETTLED" });
  const line = (await admin.from("calculation_lines").select("calculation_id").eq("id", obligation.calculation_line_id).single()).data!;
  expect(line.calculation_id).toBe(calc.id);
  const attempt = (await admin.from("payment_attempts").select("id,obligation_id,idempotency_key,circle_tx_id,state").eq("obligation_id", obligation.id).single()).data!;
  expect(attempt).toMatchObject({ obligation_id: obligation.id, idempotency_key: obligation.idempotency_key, state: "CONFIRMED" });
  expect(attempt.circle_tx_id).toMatch(/^[0-9a-f-]{36}$/);
  expect([...rail.txOf.keys()]).toContain(attempt.circle_tx_id);
  expect(chain.receipts.get(obligation.tx_hash)?.chainId).toBe(5042002);
  const events = (await admin.from("audit_events").select("entity_id,event,correlation_id,refs").eq("company_id", company.id)).data!;
  expect(events.some(e => e.correlation_id === importCorrelation && e.refs.runId === run.id)).toBe(true);
  expect(events.some(e => e.correlation_id === calculationCorrelation && e.refs.calculationId === calc.id)).toBe(true);
  expect(events).toContainEqual(expect.objectContaining({ entity_id: obligation.id, event: "OBLIGATION_SETTLED", correlation_id: executor.correlationId, refs: expect.objectContaining({ txHash: obligation.tx_hash }) }));
  for (const id of [configId, proposal.executionId, run.id, batchId, obligation.id]) expect(events.some(e => e.entity_id === id)).toBe(true);
  expect((await admin.from("audit_events").update({ refs: {} }).eq("company_id", company.id)).error).not.toBeNull();
  expect((await admin.from("calculations").update({ calculation_hash: "tampered" }).eq("id", calc.id)).error).not.toBeNull();
});
